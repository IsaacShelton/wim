// File-type icons (Nerd Font glyphs) for the file tree and buffer tabs.
//
// Generated from nvim-web-devicons' default tables with the overrides in
// `~/.config/nvim/lua/dev_icons.lua`; folder glyphs come from the nvim-tree
// settings in `~/.config/nvim/init.lua`.

export interface Icon {
    glyph: string;
    /** `0xRRGGBB` */
    color: number;
}

export const DEFAULT_FILE: Icon = { glyph: '\u{f021a}', color: 0x6d8086 };
export const FOLDER_CLOSED = '\u{e6ad}';
export const FOLDER_OPEN = '\u{eaf6}';
export const FOLDER_EMPTY = '\u{ea83}';
export const FOLDER_EMPTY_OPEN = '\u{ebdf}';

type Row = [name: string, glyph: number, color: number];

function index(rows: Row[]): Map<string, Icon> {
    return new Map(rows.map(([name, glyph, color]) => [name, { glyph: String.fromCodePoint(glyph), color }]));
}

/** The icon for a file name: an exact name match first (`Cargo.toml`,
 * `.gitignore`), then the longest matching extension (`d.ts` before `ts`). */
export function forFile(name: string): Icon {
    const exact = BY_NAME.get(name) ?? BY_NAME.get(name.toLowerCase());
    if (exact) return exact;
    for (let i = name.indexOf('.'); i >= 0; i = name.indexOf('.', i + 1)) {
        const ext = name.slice(i + 1);
        const icon = BY_EXTENSION.get(ext) ?? BY_EXTENSION.get(ext.toLowerCase());
        if (icon) return icon;
    }
    return DEFAULT_FILE;
}

